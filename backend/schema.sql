CREATE TABLE clinic_appointment_policy (
    id SMALLINT PRIMARY KEY CHECK (id=1),
    pending_requests_reserve_capacity BOOLEAN NOT NULL DEFAULT TRUE,
    pending_expiration_minutes INTEGER CHECK (pending_expiration_minutes BETWEEN 5 AND 43200),
    max_active_appointments_per_student SMALLINT CHECK (max_active_appointments_per_student BETWEEN 1 AND 100),
    student_cancellation_deadline_hours SMALLINT CHECK (student_cancellation_deadline_hours BETWEEN 0 AND 720),
    clinic_timezone VARCHAR(100),
    reminder_offsets_minutes SMALLINT[] NOT NULL DEFAULT '{}'::smallint[] CHECK (cardinality(reminder_offsets_minutes) <= 10),
    updated_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clinic_appointment_policy_timezone_check CHECK (
        (cardinality(reminder_offsets_minutes)=0 AND student_cancellation_deadline_hours IS NULL) OR clinic_timezone IS NOT NULL
    )
);
