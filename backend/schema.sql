-- Canonical bootstrap schema for a complete CCARS database. Apply only to an
-- empty database; the application does not run schema changes at startup.

CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR NOT NULL,
    last_name VARCHAR NOT NULL,
    email VARCHAR NOT NULL UNIQUE,
    password_hash VARCHAR NOT NULL,
    role VARCHAR NOT NULL,
    student_number VARCHAR UNIQUE,
    course VARCHAR,
    year_level VARCHAR,
    section VARCHAR,
    position VARCHAR,
    contact_number VARCHAR,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_role_check CHECK (role IN ('student', 'admin', 'super_admin')),
    CONSTRAINT users_student_number_required CHECK (role <> 'student' OR student_number IS NOT NULL)
);

CREATE TABLE staff_schedules (
    id SERIAL PRIMARY KEY,
    user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    available_date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT staff_schedules_check CHECK (end_time > start_time)
);

CREATE TABLE clinic_operating_hours (
    weekday SMALLINT PRIMARY KEY CHECK (weekday BETWEEN 0 AND 6),
    open_time TIME WITHOUT TIME ZONE,
    close_time TIME WITHOUT TIME ZONE,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clinic_operating_hours_check CHECK (
        (is_closed AND open_time IS NULL AND close_time IS NULL)
        OR (NOT is_closed AND open_time IS NOT NULL AND close_time > open_time)
    )
);

CREATE TABLE staff_schedule_exceptions (
    id SERIAL PRIMARY KEY,
    staff_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('break', 'leave', 'closure', 'unavailable')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE,
    end_time TIME WITHOUT TIME ZONE,
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT staff_schedule_exceptions_dates_check CHECK (end_date >= start_date),
    CONSTRAINT staff_schedule_exceptions_times_check CHECK (
        (start_time IS NULL AND end_time IS NULL) OR (start_time IS NOT NULL AND end_time > start_time)
    )
);

CREATE TABLE appointment_types (
    id SERIAL PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
    description VARCHAR(1000),
    duration_minutes SMALLINT NOT NULL CHECK (duration_minutes BETWEEN 5 AND 480),
    capacity_per_slot SMALLINT NOT NULL DEFAULT 1 CHECK (capacity_per_slot BETWEEN 1 AND 100),
    requires_approval BOOLEAN NOT NULL DEFAULT TRUE,
    required_information JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(required_information) = 'array'),
    scheduling_restrictions JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(scheduling_restrictions) = 'object'),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointments (
    id SERIAL PRIMARY KEY,
    reference_number VARCHAR(48) NOT NULL UNIQUE,
    user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    schedule_id INTEGER REFERENCES staff_schedules(id) ON DELETE SET NULL,
    appointment_type_id INTEGER REFERENCES appointment_types(id) ON DELETE SET NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME WITHOUT TIME ZONE NOT NULL,
    reason TEXT NOT NULL,
    additional_information JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(additional_information) = 'object'),
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointments_status_check CHECK (status IN (
        'pending', 'confirmed', 'checked_in', 'in_consultation',
        'completed', 'cancelled', 'rejected', 'no_show'
    ))
);

CREATE TABLE appointment_status_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN ('status_change', 'rescheduled')),
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    actor_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(20) NOT NULL CHECK (actor_role IN ('student', 'admin', 'super_admin', 'system')),
    reason VARCHAR(1000),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointment_reschedule_requests (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    student_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    requested_schedule_id INTEGER NOT NULL REFERENCES staff_schedules(id) ON DELETE RESTRICT,
    requested_date DATE NOT NULL,
    requested_time TIME WITHOUT TIME ZONE NOT NULL,
    student_reason VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    reviewer_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    review_reason VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointment_information_requests (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    requested_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    question VARCHAR(1000) NOT NULL CHECK (length(trim(question)) > 0),
    response VARCHAR(2000),
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'answered')),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE appointment_schedule_proposals (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    proposed_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    schedule_id INTEGER NOT NULL REFERENCES staff_schedules(id) ON DELETE RESTRICT,
    proposed_date DATE NOT NULL,
    proposed_time TIME WITHOUT TIME ZONE NOT NULL,
    message VARCHAR(1000),
    response_reason VARCHAR(1000),
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected', 'expired')),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE notifications (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    appointment_id INTEGER REFERENCES appointments(id) ON DELETE SET NULL,
    type VARCHAR(48) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(500) NOT NULL,
    dedupe_key VARCHAR(180) NOT NULL UNIQUE,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT notifications_read_state_check CHECK (is_read = (read_at IS NOT NULL))
);

CREATE TABLE clinic_attendance_policy (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    self_checkin_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    timezone VARCHAR(100),
    opens_minutes_before SMALLINT CHECK (opens_minutes_before BETWEEN 0 AND 1440),
    closes_minutes_after SMALLINT CHECK (closes_minutes_after BETWEEN 0 AND 1440),
    updated_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT clinic_attendance_policy_window_check CHECK (
        NOT self_checkin_enabled OR
        (timezone IS NOT NULL AND opens_minutes_before IS NOT NULL AND closes_minutes_after IS NOT NULL)
    )
);
