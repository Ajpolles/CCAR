CREATE INDEX idx_waiting_queue_history_entry ON clinic_waiting_queue_history (queue_entry_id, created_at, id);
CREATE UNIQUE INDEX idx_reschedule_requests_one_pending ON appointment_reschedule_requests (appointment_id) WHERE status = 'pending';
CREATE INDEX idx_patient_records_student ON patient_records (user_id);
CREATE INDEX idx_patient_record_amendments_record ON patient_record_amendments (record_id, created_at, id);
