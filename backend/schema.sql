CREATE TABLE clinic_appointment_policy_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    previous_values JSONB NOT NULL,
    new_values JSONB NOT NULL,
    changed_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    reason VARCHAR(1000) NOT NULL CHECK (length(trim(reason)) > 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointment_attendance (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL CHECK (status IN ('checked_in', 'late', 'no_show', 'excused')),
    checked_in_at TIMESTAMP WITHOUT TIME ZONE,
    recorded_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    reason VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointment_attendance_timestamp_check CHECK (
        (status IN ('checked_in','late') AND checked_in_at IS NOT NULL)
        OR (status IN ('no_show','excused') AND checked_in_at IS NULL)
    ),
    CONSTRAINT appointment_attendance_reason_check CHECK (status NOT IN ('no_show','excused') OR length(trim(COALESCE(reason,''))) > 0)
);

CREATE TABLE appointment_attendance_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    previous_status VARCHAR(16),
    new_status VARCHAR(16) NOT NULL CHECK (new_status IN ('checked_in', 'late', 'no_show', 'excused')),
    actor_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(20) NOT NULL CHECK (actor_role IN ('student', 'admin', 'super_admin', 'system')),
    reason VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE clinic_waiting_queue (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE RESTRICT,
    queue_date DATE NOT NULL,
    position INTEGER NOT NULL CHECK (position > 0),
    status VARCHAR(24) NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'called', 'in_consultation', 'completed', 'removed')),
    assigned_staff_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    added_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    called_at TIMESTAMP WITH TIME ZONE,
    removed_at TIMESTAMP WITH TIME ZONE,
    removal_reason VARCHAR(1000)
);

CREATE TABLE clinic_waiting_queue_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    queue_entry_id BIGINT NOT NULL REFERENCES clinic_waiting_queue(id) ON DELETE RESTRICT,
    previous_status VARCHAR(16),
    new_status VARCHAR(24) NOT NULL CHECK (new_status IN ('waiting', 'called', 'in_consultation', 'completed', 'removed')),
    actor_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(20) NOT NULL CHECK (actor_role IN ('student', 'admin', 'super_admin', 'system')),
    reason VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patient_records (
    id SERIAL PRIMARY KEY,
    user_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    appointment_id INTEGER NOT NULL,
    visit_date DATE NOT NULL,
    diagnosis_notes TEXT,
    consultation_notes TEXT,
    record_status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (record_status IN ('draft', 'finalized')),
    chief_complaint TEXT,
    history_of_present_illness TEXT,
    relevant_medical_history TEXT,
    vital_signs JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(vital_signs)='object'),
    clinical_assessment TEXT,
    diagnosis TEXT,
    treatment TEXT,
    medication_information TEXT,
    instructions TEXT,
    follow_up_recommendation TEXT,
    provider_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    finalized_at TIMESTAMP WITHOUT TIME ZONE,
    finalized_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT patient_records_appointment_id_fkey
        FOREIGN KEY (appointment_id) REFERENCES appointments(id),
    CONSTRAINT uk_appointment_id UNIQUE (appointment_id)
);

CREATE TABLE staff_clinical_permissions (
    user_id INTEGER PRIMARY KEY REFERENCES users(user_id) ON DELETE RESTRICT,
    can_view_records BOOLEAN NOT NULL DEFAULT FALSE,
    can_document BOOLEAN NOT NULL DEFAULT FALSE,
    can_finalize BOOLEAN NOT NULL DEFAULT FALSE,
    granted_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT staff_clinical_permissions_implication_check CHECK (
        (NOT can_document OR can_view_records) AND (NOT can_finalize OR can_document)
    )
);

CREATE TABLE staff_clinical_permission_history (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    previous_permissions JSONB NOT NULL DEFAULT '{}'::jsonb,
    new_permissions JSONB NOT NULL,
    changed_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    reason VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patient_record_amendments (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    record_id INTEGER NOT NULL REFERENCES patient_records(id) ON DELETE RESTRICT,
    previous_values JSONB NOT NULL,
    amended_values JSONB NOT NULL,
    reason VARCHAR(1000) NOT NULL CHECK (length(trim(reason)) > 0),
    amended_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointment_follow_ups (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    record_id INTEGER REFERENCES patient_records(id) ON DELETE RESTRICT,
    requested_by INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    recommendation TEXT,
    requested_date DATE,
    status VARCHAR(16) NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'scheduled', 'declined', 'completed', 'cancelled')),
    related_appointment_id INTEGER REFERENCES appointments(id) ON DELETE RESTRICT,
    reviewed_by INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    review_reason VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointment_waitlists (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    appointment_type_id INTEGER NOT NULL REFERENCES appointment_types(id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    preferred_start_time TIME WITHOUT TIME ZONE,
    preferred_end_time TIME WITHOUT TIME ZONE,
    status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'notified', 'closed')),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointment_waitlists_dates_check CHECK (end_date >= start_date),
    CONSTRAINT appointment_waitlists_times_check CHECK (
        (preferred_start_time IS NULL AND preferred_end_time IS NULL)
        OR (preferred_start_time IS NOT NULL AND preferred_end_time > preferred_start_time)
    )
);

CREATE TABLE appointment_waitlist_offers (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    waitlist_id BIGINT NOT NULL REFERENCES appointment_waitlists(id) ON DELETE RESTRICT,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'notified' CHECK (status IN ('notified', 'accepted', 'declined', 'expired', 'cancelled')),
    notification_id BIGINT REFERENCES notifications(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP WITHOUT TIME ZONE,
    UNIQUE(waitlist_id, appointment_id)
);

CREATE UNIQUE INDEX idx_appointment_follow_ups_one_active
    ON appointment_follow_ups(requested_by, appointment_id) WHERE status IN ('requested', 'scheduled');

CREATE TABLE activity_logs (
    id SERIAL PRIMARY KEY,
    actor_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    actor_role VARCHAR(20) NOT NULL,
    action VARCHAR(255) NOT NULL,
    details JSONB,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT activity_logs_actor_role_check CHECK (actor_role IN (
        'user', 'student', 'admin', 'super_admin', 'system'
    ))
);

CREATE INDEX idx_activity_logs_actor ON activity_logs (actor_role, actor_id);
