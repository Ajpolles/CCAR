CREATE UNIQUE INDEX idx_appointment_waitlists_one_open ON appointment_waitlists (user_id, appointment_type_id) WHERE status IN ('active', 'notified');
CREATE INDEX idx_staff_schedules_admin_date ON staff_schedules (user_id, available_date);
CREATE INDEX idx_schedule_exceptions_dates ON staff_schedule_exceptions (start_date, end_date) WHERE is_active = TRUE;
